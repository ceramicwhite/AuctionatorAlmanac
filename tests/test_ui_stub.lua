local H = require("harness")
local Stub = require("ui_stub")
local test = H.test

test("stub resolves anchors into rectangles", function()
  local env = Stub.new()
  local win = env.CreateFrame("Frame", "W", env.UIParent)
  win:SetSize(800, 600)
  win:SetPoint("TOPLEFT", env.UIParent, "TOPLEFT", 100, -50)
  local left = env.CreateFrame("Frame", nil, win)
  left:SetWidth(150)
  left:SetPoint("TOPLEFT", win, "TOPLEFT", 10, -30)
  left:SetPoint("BOTTOMLEFT", win, "BOTTOMLEFT", 10, 10)
  local right = env.CreateFrame("Frame", nil, win)
  right:SetWidth(300)
  right:SetPoint("TOPRIGHT", win, "TOPRIGHT", -10, -30)
  right:SetPoint("BOTTOMRIGHT", win, "BOTTOMRIGHT", -10, 10)
  local middle = env.CreateFrame("Frame", nil, win)
  middle:SetPoint("TOPLEFT", left, "TOPRIGHT", 6, 0)
  middle:SetPoint("BOTTOMRIGHT", right, "BOTTOMLEFT", -6, 0)

  local l, t, w, h = Stub.rect(win)
  H.eq({ l, t, w, h }, { 100, 50, 800, 600 })
  H.eq({ Stub.rect(left) }, { 110, 80, 150, 560 })
  H.eq({ Stub.rect(right) }, { 590, 80, 300, 560 })
  H.eq({ Stub.rect(middle) }, { 266, 80, 318, 560 })

  win:SetSize(1000, 700)
  H.eq({ Stub.rect(middle) }, { 266, 80, 518, 660 }, "the middle follows the window")
  H.falsy(Stub.overlaps(left, middle))
  H.falsy(Stub.overlaps(middle, right))
  H.truthy(Stub.within(middle, win))
end)

test("settle fires OnSizeChanged once per change and reaches children", function()
  local env = Stub.new()
  local win = env.CreateFrame("Frame", nil, env.UIParent)
  win:SetSize(400, 300)
  win:SetPoint("CENTER")
  local child = env.CreateFrame("Frame", nil, win)
  child:SetAllPoints(win)
  local seen = {}
  child:SetScript("OnSizeChanged", function(_, w, h) seen[#seen + 1] = string.format("%dx%d", w, h) end)
  Stub.settle(env)
  Stub.resize(env, win, 500, 350)
  Stub.settle(env)
  H.eq(seen, { "400x300", "500x350" })
end)

test("only real widget methods exist", function()
  local env = Stub.new()
  local f = env.CreateFrame("Frame", nil, env.UIParent)
  H.eq(f.SetSizee, nil)
  H.throws(function() f:SetBackdropBorderColour(1, 1, 1) end, "typo'd method must fail")
  H.nothrows(function() f:SetFrameStrata("HIGH") end)
end)

test("scripts can be fired and hooks run after", function()
  local env = Stub.new()
  local b = env.CreateFrame("Button", nil, env.UIParent)
  local order = {}
  b:SetScript("OnClick", function() order[#order + 1] = "script" end)
  b:HookScript("OnClick", function() order[#order + 1] = "hook" end)
  b:Click()
  H.eq(order, { "script", "hook" })
end)
