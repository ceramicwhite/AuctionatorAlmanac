local H = require("harness")
local Stub = require("ui_stub")
local test = H.test

local FILES = { "Core/Init.lua", "Core/Format.lua", "UI/Theme.lua", "UI/Widgets.lua", "UI/VirtualList.lua", "UI/Table.lua", "UI/Window.lua" }

local function boot(savedWindow)
  local env = Stub.new()
  env.C_Timer = H.fakeTimer()
  local A, leaks = H.newUI(FILES, env)
  A.db = A.InitDB(savedWindow and { version = 1, window = savedWindow } or nil)
  -- the one piece of the controller the window reads: which item is selected
  A.Controller = { state = {} }
  function A.Controller.Select(id)
    A.Controller.state.selected = id
    A.Bus.Fire("SELECTION_CHANGED", id)
  end
  return A, env, leaks
end

-- Open the window on the Search page with an item selected, so the detail panel and its divider are there.
local function withDetail(A, env, mode)
  local win = A.UI.Window.Get()
  win:Show()
  A.UI.Window.SetMode(mode or "search")
  A.Controller.Select(12359)
  Stub.settle(env)
  return win
end

