-- ---------------------------------------------------------------------------
-- Hiding the item list, and dragging the divider
-- ---------------------------------------------------------------------------
local function bodyRight(win) return win.body:GetRight() end

test("a button on the divider hides the item list and gives its room to the detail panel", function()
  local A, env = boot()
  local win = A.UI.Window.Get()
  win:Show()
  Stub.resize(env, win, 1200, 700)
  H.truthy(win.resultsPanel:IsShown())
  H.truthy(win.collapseButton:IsShown())
  local before = win.detailPanel:GetWidth()
  win.collapseButton:Click()
  Stub.settle(env)
  H.truthy(A.UI.Window.IsCollapsed())
  H.falsy(win.resultsPanel:IsShown())
  H.truthy(win.detailPanel:GetWidth() > before + 300, "the detail panel took over the list's room")
  H.eq(win.catPanel:GetWidth(), 150, "categories keep their width")
  H.truthy(Stub.within(win.detailPanel, win.body))
  H.falsy(Stub.overlaps(win.catPanel, win.detailPanel))
  H.near(win.detailPanel:GetLeft() - win.catPanel:GetRight(), 6, 0.5, "same gap as before")
  H.near(win.detailPanel:GetRight(), bodyRight(win), 0.5)
  win.collapseButton:Click()
  Stub.settle(env)
  H.falsy(A.UI.Window.IsCollapsed())
  H.truthy(win.resultsPanel:IsShown())
  H.near(win.detailPanel:GetWidth(), before, 0.5, "back to the width it had")
end)

test("the divider button says what it will do", function()
  local A, env = boot()
  local win = A.UI.Window.Get()
  win:Show()
  local open = win.collapseButton.label:GetText()
  win.collapseButton:Click()
  local closed = win.collapseButton.label:GetText()
  H.truthy(open ~= closed, "the arrow flips")
  H.truthy(win.collapseButton.tip and win.collapseButton.tip:lower():find("show", 1, true), win.collapseButton.tip)
  win.collapseButton:Click()
  H.truthy(win.collapseButton.tip:lower():find("hide", 1, true), win.collapseButton.tip)
end)

test("the divider button stays in the gap and inside the window in both states", function()
  local A, env = boot()
  local win = A.UI.Window.Get()
  win:Show()
  for _, size in ipairs(SIZES) do
    Stub.resize(env, win, size[1], size[2])
    for _, collapsed in ipairs({ false, true }) do
      A.UI.Window.SetCollapsed(collapsed)
      Stub.settle(env)
      local label = size[1] .. "x" .. size[2] .. (collapsed and " collapsed" or "")
      H.truthy(Stub.within(win.collapseButton, win.body), "button inside the body at " .. label)
      H.truthy(Stub.within(win.splitter, win.body), "splitter inside the body at " .. label)
      H.truthy(Stub.within(win.detailPanel, win.body), "detail inside at " .. label)
      H.falsy(Stub.overlaps(win.catPanel, win.detailPanel), "categories and detail at " .. label)
      if collapsed then
        H.falsy(win.resultsPanel:IsShown())
        H.near(win.detailPanel:GetWidth(), win.body:GetWidth() - 150 - 6, 0.5, "fills the rest at " .. label)
      else
        H.falsy(Stub.overlaps(win.resultsPanel, win.detailPanel), "results and detail at " .. label)
      end
    end
  end
end)

