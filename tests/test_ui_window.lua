    H.falsy(Stub.overlaps(win.statusBar, win.searchRow))
    H.falsy(Stub.overlaps(win.searchRow, win.body))
    H.falsy(Stub.overlaps(win.grip, win.body), "the grip sits in the margin at " .. label)
  end
end)

