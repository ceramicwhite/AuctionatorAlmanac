test("ExpandResults brings the list back only when it was hidden", function()
  local A, env = boot()
  local win = A.UI.Window.Get()
  win:Show()
  local shown = 0
  A.Bus.On("LAYOUT_CHANGED", function() shown = shown + 1 end)
  A.UI.Window.ExpandResults()
  H.eq(shown, 0, "nothing to do when it is already showing")
  A.UI.Window.SetCollapsed(true)
  H.eq(shown, 1)
  A.UI.Window.ExpandResults()
  H.falsy(A.UI.Window.IsCollapsed())
  H.truthy(win.resultsPanel:IsShown())
  H.eq(shown, 2)
end)

test("dragging the divider resizes the detail panel and remembers the width", function()
  local A, env = boot()
  local win = A.UI.Window.Get()
  win:Show()
  Stub.resize(env, win, 1400, 800)
  local divider = win.splitter
  H.truthy(divider)
  local right = bodyRight(win)
  Stub.fire(divider, "OnDragStart")
  H.truthy(divider:GetScript("OnUpdate"), "follows the mouse while dragging")
  env.GetCursorPosition = function() return right - 700, 300 end
  divider:GetScript("OnUpdate")(divider, 0.016)
  Stub.settle(env)
  H.near(win.detailPanel:GetWidth(), 700 - 3, 1, "the divider sits under the cursor")
  Stub.fire(divider, "OnDragStop")
  H.falsy(divider:GetScript("OnUpdate"))
  H.near(A.db.window.detailW, win.detailPanel:GetWidth(), 1)
  H.truthy(win.resultsPanel:GetWidth() >= 300)
  H.falsy(Stub.overlaps(win.resultsPanel, win.detailPanel))
end)

test("the divider cannot squeeze either side below a usable size", function()
  local A, env = boot()
  local win = A.UI.Window.Get()
  win:Show()
  Stub.resize(env, win, 1400, 800)
  local right = bodyRight(win)
  Stub.fire(win.splitter, "OnDragStart")
  env.GetCursorPosition = function() return right - 10, 0 end
  win.splitter:GetScript("OnUpdate")(win.splitter, 0.016)
  Stub.settle(env)
  H.eq(win.detailPanel:GetWidth(), 330, "no narrower than the detail minimum")
  env.GetCursorPosition = function() return right - 5000, 0 end
  win.splitter:GetScript("OnUpdate")(win.splitter, 0.016)
  Stub.settle(env)
  H.truthy(win.resultsPanel:GetWidth() >= 299.5, "the list keeps at least 300: " .. win.resultsPanel:GetWidth())
  Stub.fire(win.splitter, "OnDragStop")
end)

