test("every region stays inside the window and never overlaps at any size", function()
  local A, env = boot()
  local win = withDetail(A, env)
  for _, size in ipairs(SIZES) do
    Stub.resize(env, win, size[1], size[2])
    local label = size[1] .. "x" .. size[2]
