local H = require("harness")
local test = H.test

local function load(env) return H.newA({ "Core/Init.lua", "Core/Format.lua" }, env).Format end

test("Money formats gold silver copper", function()
  local F = load()
  H.eq(F.Money(11240, { plain = true }), "1g 12s 40c")
  H.eq(F.Money(5, { plain = true }), "5c")
  H.eq(F.Money(0, { plain = true }), "0c")
  H.eq(F.Money(10000, { plain = true }), "1g")
  H.eq(F.Money(10005, { plain = true }), "1g 0s 5c", "middle zero units are kept")
  H.eq(F.Money(-250, { plain = true }), "-2s 50c")
end)

test("Money short keeps the two most significant units", function()
  local F = load()
  H.eq(F.Money(1234567, { plain = true, short = true }), "123g 45s")
  H.eq(F.Money(11240, { plain = true, short = true }), "1g 12s")
  H.eq(F.Money(4550, { plain = true, short = true }), "45s 50c")
  H.eq(F.Money(7, { plain = true, short = true }), "7c")
end)

test("Money colors units and treats nil as a dash", function()
  local F = load()
  H.eq(F.Money(11240), "|cffffd7001g|r |cffc7c7cf12s|r |cffeda55f40c|r")
  H.eq(F.Money(nil), "—")
  H.eq(F.Money(nil, { plain = true }), "—")
  H.eq(F.Money(12.9, { plain = true }), "12c", "fractions floor")
end)

test("Ago formats durations", function()
  local F = load()
  H.eq(F.Ago(45), "45s")
  H.eq(F.Ago(300), "5m")
  H.eq(F.Ago(8040), "2h 14m")
  H.eq(F.Ago(7200), "2h")
  H.eq(F.Ago(93600), "1d 2h")
  H.eq(F.Ago(86400 * 3), "3d")
  H.eq(F.Ago(nil), "never")
  H.eq(F.Ago(-5), "0s", "negative clamps")
end)

test("Freshness buckets", function()
  local F = load()
  H.eq(F.Freshness(3600), "fresh")
  H.eq(F.Freshness(3600 * 7), "ok")
  H.eq(F.Freshness(3600 * 30), "stale")
  H.eq(F.Freshness(3600 * 100), "old")
  H.eq(F.Freshness(nil), "old")
end)

test("Percent formats signed whole percents", function()
  local F = load()
  H.eq(F.Percent(0.083), "+8%")
  H.eq(F.Percent(-0.031), "-3%")
  H.eq(F.Percent(0.001), "0%")
  H.eq(F.Percent(nil), "—")
end)

test("Change colors rises green and falls red", function()
  local F = load()
  H.eq(F.Change(0.083), "|cff5fd35f+8%|r")
  H.eq(F.Change(-0.031), "|cffff6a5a-3%|r")
  H.eq(F.Change(nil), "|cff8a8a8a—|r")
end)

test("Count adds thousands separators", function()
  local F = load()
  H.eq(F.Count(14203), "14,203")
  H.eq(F.Count(999), "999")
  H.eq(F.Count(1234567), "1,234,567")
  H.eq(F.Count(nil), "—")
end)

test("Date drops the leading zero", function()
  local F = load({ date = function() return "Nov 08" end })
  H.eq(F.Date(1), "Nov 8")
end)

test("Quality colors", function()
  local F = load()
  local r, g, b, hex = F.QualityColor(1)
  H.eq(hex, "ffffff")
  H.eq(select(4, F.QualityColor(2)), "1eff00")
  H.eq(select(4, F.QualityColor(3)), "0070dd")
  H.eq(select(4, F.QualityColor(4)), "a335ee")
  H.eq(select(4, F.QualityColor(99)), "ffffff", "unknown falls back to white")
  H.eq(select(4, F.QualityColor(nil)), "ffffff")
  H.near(select(2, F.QualityColor(2)), 1)
  H.eq(F.ColorName("Thorium Bar", 2), "|cff1eff00Thorium Bar|r")
end)
